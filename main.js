function applyLanguage(lang) {
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const entry = translations[key];
    if (!entry) return;
    el.textContent = entry[lang];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    const entry = translations[key];
    if (!entry) return;
    el.innerHTML = entry[lang];
  });

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && translations['meta-desc']) metaDesc.setAttribute('content', translations['meta-desc'][lang]);

  document.querySelectorAll('.lang-switch__btn').forEach(btn => {
    const active = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });

  try { localStorage.setItem('nf-lang', lang); } catch (e) { /* ignore storage errors */ }
}

document.addEventListener('DOMContentLoaded', () => {

  const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---------- Language ---------- */
  let savedLang = 'pt';
  try { savedLang = localStorage.getItem('nf-lang') || 'pt'; } catch (e) { /* ignore */ }
  applyLanguage(savedLang);

  document.querySelectorAll('.lang-switch__btn').forEach(btn => {
    btn.addEventListener('click', () => applyLanguage(btn.getAttribute('data-lang')));
  });

  /* ---------- Year ---------- */
  const yearEl = document.getElementById('year');
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  /* ---------- Mobile nav ---------- */
  const burger = document.getElementById('burger');
  const links = document.querySelector('.nav__links');
  if (burger && links) {
    burger.addEventListener('click', () => {
      const open = links.classList.toggle('is-open');
      burger.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    links.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
      links.classList.remove('is-open');
      burger.setAttribute('aria-expanded', 'false');
    }));
  }

  /* ---------- Build a grid of squares ---------- */
  function buildGrid(el, { rows, cols, color, pulse = true }) {
    if (!el) return;
    el.style.gridTemplateColumns = `repeat(${cols}, 1fr)`;
    el.style.gridTemplateRows = `repeat(${rows}, 1fr)`;
    const total = rows * cols;
    for (let i = 0; i < total; i++) {
      const sq = document.createElement('div');
      sq.style.background = color;
      sq.style.borderRadius = '2px';
      if (pulse && !prefersReduced) {
        sq.classList.add('sq');
        sq.style.animationDelay = `${(Math.random() * 3).toFixed(2)}s`;
      }
      el.appendChild(sq);
    }
  }

  buildGrid(document.getElementById('gridOrange'), { rows: 4, cols: 5, color: 'var(--orange)' });
  buildGrid(document.getElementById('gridLavender'), { rows: 4, cols: 4, color: 'var(--lavender)' });

  /* ---------- mini data-grid (used near "why banking" + contact) ---------- */
  function buildMiniGrid(el, seed = 0) {
    if (!el) return;
    const cells = [];
    for (let i = 0; i < 25; i++) {
      const cell = document.createElement('i');
      el.appendChild(cell);
      cells.push(cell);
    }
    if (prefersReduced) return;
    // sweep a "data pulse" across the grid, like cells lighting up in sequence
    let step = seed;
    setInterval(() => {
      cells.forEach((c, idx) => {
        const active = (idx + step) % 25 < 3;
        c.style.background = active ? 'var(--orange)' : 'var(--border)';
        c.style.transition = 'background 0.5s ease';
      });
      step = (step + 1) % 25;
    }, 260);
  }

  buildMiniGrid(document.getElementById('miniGrid1'), 0);

  buildGrid(document.getElementById('miniGrid2'), { rows: 6, cols: 6, color: 'var(--lavender)', pulse: false });

  /* ---------- Scroll reveal ---------- */
  const revealTargets = document.querySelectorAll(
    '.about, .whyfin, .skill-card, .timeline__item, .project-card, .roadmap-card, .contact__links'
  );
  revealTargets.forEach(el => el.classList.add('reveal'));

  if ('IntersectionObserver' in window && !prefersReduced) {
    const io = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          io.unobserve(entry.target);
        }
      });
    }, { threshold: 0.15 });
    revealTargets.forEach(el => io.observe(el));
  } else {
    revealTargets.forEach(el => el.classList.add('is-visible'));
  }

});
